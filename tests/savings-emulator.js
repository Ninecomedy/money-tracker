import assert from 'node:assert/strict';
import { initializeApp, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, createUserWithEmailAndPassword, signInWithEmailAndPassword } from 'firebase/auth';
import * as firestore from 'firebase/firestore';
import { commitSavingsTransfer, walletTotals } from '../savings.js';
const apps=['wallet','device','other','anonymous'].map(name=>initializeApp({projectId:'demo-money-tracker',apiKey:'demo-key'},name));
const auths=apps.map(app=>getAuth(app));
const databases=apps.map(app=>firestore.getFirestore(app));
auths.forEach(auth=>connectAuthEmulator(auth,'http://127.0.0.1:9099',{disableWarnings:true}));
databases.forEach(database=>firestore.connectFirestoreEmulator(database,'127.0.0.1',8080));
const suffix=Date.now();
try {
  const first=await createUserWithEmailAndPassword(auths[0],`savings_${suffix}@money-tracker.invalid`,'Emulator-only-test');
  await signInWithEmailAndPassword(auths[1],first.user.email,'Emulator-only-test');
  await createUserWithEmailAndPassword(auths[2],`other_${suffix}@money-tracker.invalid`,'Emulator-only-test');
  const uid=first.user.uid;
  const settings=firestore.doc(databases[0],'users',uid,'settings','main');
  const history=firestore.collection(databases[0],'users',uid,'savingsTransfers');
  await assert.rejects(commitSavingsTransfer(databases[0],uid,1,'add',firestore),/ค่าเริ่มต้น/);
  await firestore.setDoc(settings,{opening:250,reserve:50,updatedAt:new Date().toISOString()});
  await commitSavingsTransfer(databases[0],uid,20,'add',firestore);
  assert.equal((await firestore.getDoc(settings)).data().reserve,70);
  assert.equal((await firestore.getDocs(history)).size,1);
  await commitSavingsTransfer(databases[1],uid,20,'remove',firestore);
  assert.equal((await firestore.getDoc(settings)).data().reserve,50);
  await assert.rejects(commitSavingsTransfer(databases[0],uid,201,'add',firestore),/ไม่เพียงพอ/);
  await assert.rejects(commitSavingsTransfer(databases[0],uid,51,'remove',firestore),/ไม่เพียงพอ/);
  assert.equal((await firestore.getDocs(history)).size,2);
  const results=await Promise.allSettled([0,1].map(index=>commitSavingsTransfer(databases[index],uid,150,'add',firestore)));
  assert.equal(results.filter(result=>result.status==='fulfilled').length,1);
  assert.equal((await firestore.getDoc(settings)).data().reserve,200);
  assert.equal((await firestore.getDocs(history)).size,3);
  const totals=walletTotals({...((await firestore.getDoc(settings)).data()),items:[]});
  assert.equal(totals.balance,250);assert.equal(totals.free,50);assert.equal(totals.income,0);assert.equal(totals.expense,0);
  const denied=operation=>assert.rejects(operation,error=>error.code==='permission-denied');
  await denied(()=>firestore.getDocs(firestore.collection(databases[3],'users',uid,'savingsTransfers')));
  await denied(()=>firestore.getDoc(firestore.doc(databases[2],'users',uid,'settings','main')));
  await denied(()=>firestore.setDoc(firestore.doc(databases[2],'users',uid,'settings','main'),{opening:999,reserve:0,updatedAt:new Date().toISOString()}));
  await denied(()=>firestore.getDocs(firestore.collection(databases[2],'users',uid,'savingsTransfers')));
  await denied(()=>commitSavingsTransfer(databases[2],uid,1,'remove',firestore));
  await denied(()=>firestore.addDoc(history,{direction:'add',amount:10,before:200,after:210,date:new Date().toISOString()}));
  const record=(await firestore.getDocs(history)).docs[0];
  await denied(()=>firestore.updateDoc(record.ref,{amount:999}));
  await denied(()=>firestore.deleteDoc(record.ref));
  const entries=firestore.collection(databases[0],'users',uid,'entries');
  await firestore.addDoc(entries,{type:'income',amount:100,note:'Existing income',category:'income',date:new Date().toISOString()});
  await firestore.addDoc(entries,{type:'expense',amount:40,note:'Existing expense',category:'expense',date:new Date().toISOString()});
  const originalEntries=(await firestore.getDocs(entries)).docs.map(snapshot=>({id:snapshot.id,...snapshot.data()}));
  await commitSavingsTransfer(databases[0],uid,25,'add',firestore);
  await commitSavingsTransfer(databases[1],uid,10,'remove',firestore);
  const retainedEntries=(await firestore.getDocs(entries)).docs.map(snapshot=>({id:snapshot.id,...snapshot.data()}));
  assert.deepEqual(retainedEntries,originalEntries);
  const retainedTotals=walletTotals({...((await firestore.getDoc(settings)).data()),items:retainedEntries});
  assert.equal(retainedTotals.income,100);assert.equal(retainedTotals.expense,40);
  assert.equal(retainedTotals.balance,310);assert.equal(retainedTotals.reserve,215);assert.equal(retainedTotals.free,95);
  await assert.rejects(commitSavingsTransfer(databases[0],uid,96,'add',firestore),/ไม่เพียงพอ/);
  console.log('PASS: existing income/expense documents and totals unchanged after deposit and withdrawal; anonymous and cross-account access denied');
  await firestore.setDoc(settings,{opening:1,reserve:0.1,updatedAt:new Date().toISOString()});
  await commitSavingsTransfer(databases[0],uid,0.2,'add',firestore);
  assert.equal((await firestore.getDoc(settings)).data().reserve,0.3);
  console.log('PASS: legacy settings, add/remove, limits, decimal cents, atomic history, concurrent transfers, cross-UID denial and immutable history');
} finally {
  await Promise.all(databases.map(database=>firestore.terminate(database)));
  await Promise.all(apps.map(app=>deleteApp(app)));
}
